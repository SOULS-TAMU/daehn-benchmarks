@dataclass(frozen=True)
class TimeScaledMLPBackbone:
    """Evaluate an MLP at t/time_scale while differentiating in physical time."""

    hidden_sizes: tuple[int, ...]
    time_scale: float
    activation: Any = jax.nn.tanh

    def __post_init__(self) -> None:
        if not np.isfinite(self.time_scale) or float(self.time_scale) <= 0.0:
            raise ValueError("time_scale must be finite and positive")

    def init(self, key, input_dim, output_dim, dtype=jnp.float64):
        return MLPBackbone(
            hidden_sizes=self.hidden_sizes,
            activation=self.activation,
        ).init(key, input_dim, output_dim, dtype)

    def apply(self, parameters, inputs):
        values = jnp.asarray(inputs)
        scaled = values / jnp.asarray(self.time_scale, dtype=values.dtype)
        raw = MLPBackbone(
            hidden_sizes=self.hidden_sizes,
            activation=self.activation,
        ).apply(parameters, scaled)

        # Keep the two populations in the physical positive domain and emit
        # them at characteristic physical scales. This provides a much better
        # initial projection target than unconstrained near-zero outputs while
        # leaving the auxiliary multiplier unconstrained.
        floor = jnp.asarray(5.0e-2, dtype=raw.dtype)
        prey = floor + jnp.asarray(PREY_STATE_SCALE, raw.dtype) * jax.nn.softplus(
            raw[..., 0]
        )
        predator = floor + jnp.asarray(
            PREDATOR_STATE_SCALE, raw.dtype
        ) * jax.nn.softplus(raw[..., 1])
        multiplier = raw[..., 2:3]
        return jnp.concatenate(
            (prey[..., None], predator[..., None], multiplier), axis=-1
        )


def _positive_floor(value):
    """Bound inverse/log slopes outside the physical positive domain."""

    value = jnp.asarray(value)
    floor = jnp.asarray(5.0e-2, dtype=value.dtype)
    return jnp.maximum(value, floor), floor


def _safe_log(value):
    """C1-like linear continuation of log below a positive floor."""

    value = jnp.asarray(value)
    clipped, floor = _positive_floor(value)
    correction = jnp.minimum(value - floor, jnp.asarray(0.0, dtype=value.dtype)) / floor
    return jnp.log(clipped) + correction


def _safe_inverse(value):
    """Derivative of the continued logarithm away from its single kink."""

    clipped, _floor = _positive_floor(value)
    return jnp.reciprocal(clipped)


def _empty(_coordinates, _states, _derivatives, _parameters):
    return jnp.empty((0,), dtype=jnp.float64)


def make_lotka_volterra_system(
    horizon: float,
    *,
    projection_only: bool,
) -> DAESystem:
    """Build compatible projection and physical-residual systems.

    ``projection_only=True`` compiles a robust Euclidean projection onto the
    conserved-invariant manifold.  ``projection_only=False`` supplies the two
    original ODE residuals plus the same invariant for training metrics/losses.
    Both systems have identical coordinates, parameters, differential states,
    derivative closure, context layout, and projection-variable layout.
    """

    time = Coordinate("time", 0.0, float(horizon))
    prey = DifferentialState("prey_x", scale=PREY_STATE_SCALE)
    predator = DifferentialState("predator_y", scale=PREDATOR_STATE_SCALE)

    alpha = Parameter("alpha")
    beta = Parameter("beta")
    gamma = Parameter("gamma")
    delta = Parameter("delta")
    invariant0 = Parameter("invariant0")

    derivatives = (
        DerivativeSpec(prey, (1,)),
        DerivativeSpec(predator, (1,)),
    )

    def differential_equations(_coordinates, states, derivative_values, parameters):
        x, y = states
        # The compiled derivative closure is sorted by state name:
        # predator_y precedes prey_x, hence [dy/dt, dx/dt].
        dy_dt, dx_dt = derivative_values
        a, b, g, d, _v0 = parameters
        return jnp.asarray(
            (
                dx_dt - (a * x - b * x * y),
                dy_dt - (-g * y + d * x * y),
            )
        )

    def invariant_equation(_coordinates, states, _derivative_values, parameters):
        x, y = states
        a, b, g, d, v0 = parameters
        value = d * x - g * _safe_log(x) + b * y - a * _safe_log(y)
        return jnp.asarray((value - v0,))

    differential_block = (
        EquationBlock(
            _empty,
            size=0,
            affine_in_projection_variables=True,
            name="differential_equations_not_in_projection",
        )
        if projection_only
        else EquationBlock(
            differential_equations,
            size=2,
            affine_in_projection_variables=False,
            name="lotka_volterra_differential_equations",
        )
    )

    return DAESystem(
        coordinates=(time,),
        differential_states=(prey, predator),
        algebraic_states=(),
        parameters=(alpha, beta, gamma, delta, invariant0),
        derivatives=derivatives,
        differential_equations=differential_block,
        algebraic_equalities=EquationBlock(
            invariant_equation,
            size=1,
            affine_in_projection_variables=False,
            name="lotka_volterra_invariant",
        ),
        algebraic_inequalities=EquationBlock(
            _empty,
            size=0,
            affine_in_projection_variables=True,
            name="no_inequalities",
        ),
        name=(
            "lotka_volterra_invariant_projection"
            if projection_only
            else "lotka_volterra_physical_system"
        ),
    )


class LotkaVolterraTrainer(WeightedLossTrainerMixin, DAETrainer):
    """Use invariant-only projection but report/train on the full physical ODE."""

    def __init__(self, *, physical_system: DAESystem, **kwargs):
        self.physical_system = physical_system
        super().__init__(**kwargs)

    def _physical_blocks(self, coordinates, states, derivatives, physical_parameters):
        system = self.physical_system
        differential = jax.vmap(system.differential_equations.function)(
            coordinates, states, derivatives, physical_parameters
        )
        algebraic = jax.vmap(system.algebraic_equalities.function)(
            coordinates, states, derivatives, physical_parameters
        )
        inequalities = jax.vmap(system.algebraic_inequalities.function)(
            coordinates, states, derivatives, physical_parameters
        )
        differential = jnp.asarray(differential).reshape((coordinates.shape[0], -1))
        algebraic = jnp.asarray(algebraic).reshape((coordinates.shape[0], -1))
        inequalities = jnp.asarray(inequalities).reshape((coordinates.shape[0], -1))
        positive_inequalities = jnp.maximum(inequalities, 0.0)
        combined = jnp.concatenate(
            (differential, algebraic, positive_inequalities), axis=-1
        )
        return differential, algebraic, positive_inequalities, combined


def _read_split_array(archive: np.lib.npyio.NpzFile, *names: str) -> np.ndarray:
    for name in names:
        if name in archive.files:
            return np.asarray(archive[name], dtype=np.int64).reshape(-1)
    raise KeyError(f"none of the split keys {names!r} exists in splits.npz")


def _validate_indices(indices: np.ndarray, count: int, name: str) -> None:
    if indices.size == 0:
        raise ValueError(f"{name} split is empty")
    if np.any(indices < 0) or np.any(indices >= count):
        raise ValueError(f"{name} split contains indices outside [0, {count})")
    if np.unique(indices).size != indices.size:
        raise ValueError(f"{name} split contains duplicate indices")


def load_dataset(data_dir: Path) -> LoadedDataset:
    """Load and rigorously validate the output produced by script 10."""

    data_path = data_dir / "data.npz"
    splits_path = data_dir / "splits.npz"
    if not data_path.is_file():
        raise FileNotFoundError(f"missing DAEHN dataset: {data_path}")
    if not splits_path.is_file():
        raise FileNotFoundError(f"missing split file: {splits_path}")

    data = DAEData.load(data_path)
    coordinates = np.asarray(data.coordinates, dtype=np.float64)
    parameters = np.asarray(data.parameters, dtype=np.float64)
    states = np.asarray(data.states, dtype=np.float64)
    derivatives = None if data.derivatives is None else np.asarray(data.derivatives, dtype=np.float64)

    count = int(coordinates.shape[0])
    expected_shapes = {
        "coordinates": (count, 1),
        "parameters": (count, 5),
        "states": (count, 3),
        "derivatives": (count, 2),
    }
    actual_shapes = {
        "coordinates": coordinates.shape,
        "parameters": parameters.shape,
        "states": states.shape,
        "derivatives": None if derivatives is None else derivatives.shape,
    }
    for name, expected in expected_shapes.items():
        if actual_shapes[name] != expected:
            raise ValueError(
                f"{name} has shape {actual_shapes[name]}, expected {expected}; "
                "regenerate the dataset with script 10"
            )
    if count < 3:
        raise ValueError("the dataset must contain at least three samples")
    for name, values in (
        ("coordinates", coordinates),
        ("parameters", parameters),
        ("states", states),
        ("derivatives", derivatives),
    ):
        if not np.all(np.isfinite(values)):
            raise ValueError(f"{name} contains non-finite values")

    if np.any(states[:, :2] <= 0.0):
        raise ValueError("prey and predator values must remain strictly positive")
    if not np.allclose(states[:, 2], 0.0, atol=1.0e-12, rtol=0.0):
        raise ValueError("script-10 lambda_invariant targets are expected to be zero")
    if not np.all(np.diff(coordinates[:, 0]) > 0.0):
        raise ValueError("dataset coordinates must be strictly increasing")

    # Every row should describe the same physical system and invariant level.
    if not np.allclose(parameters, parameters[:1], rtol=0.0, atol=1.0e-12):
        raise ValueError("all parameter rows must be identical for this single trajectory")

    alpha, beta, gamma, delta, invariant0 = parameters[0]
    x = states[:, 0]
    y = states[:, 1]
    invariant = delta * x - gamma * np.log(x) + beta * y - alpha * np.log(y)
    max_invariant_residual = float(np.max(np.abs(invariant - invariant0)))
    if max_invariant_residual > 1.0e-7:
        raise ValueError(
            "dataset does not satisfy the requested invariant accurately: "
            f"max |V-V0|={max_invariant_residual:.6e}"
        )

    with np.load(splits_path) as split_archive:
        train = _read_split_array(split_archive, "train_indices", "train")
        validation = _read_split_array(
            split_archive, "validation_indices", "validation"
        )
        test = _read_split_array(split_archive, "test_indices", "test")

    _validate_indices(train, count, "training")
    _validate_indices(validation, count, "validation")
    _validate_indices(test, count, "test")
    if np.intersect1d(train, validation).size:
        raise ValueError("training and validation splits overlap")
    if np.intersect1d(train, test).size:
        raise ValueError("training and test splits overlap")
    if np.intersect1d(validation, test).size:
        raise ValueError("validation and test splits overlap")

    metadata_path = data_dir / "metadata.json"
    metadata: dict[str, Any] = {}
    if metadata_path.is_file():
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))

    horizon = float(coordinates[-1, 0] - coordinates[0, 0])
    if horizon <= 0.0:
        raise ValueError("the coordinate horizon must be positive")
    time_step = float(np.median(np.diff(coordinates[:, 0])))
    if not np.isfinite(time_step) or time_step <= 0.0:
        raise ValueError("could not infer a positive dataset time step")

    print("Loaded Lotka--Volterra dataset.")
    print(f"  data directory: {data_dir.resolve()}")
    print(f"  samples: {count}")
    print(
        "  split counts: "
        f"train={train.size}, validation={validation.size}, test={test.size}"
    )
    print(f"  horizon: {horizon:.8g}")
    print(f"  inferred time step: {time_step:.8e}")
    print(f"  max data |V-V0|: {max_invariant_residual:.6e}")

    return LoadedDataset(
        data=data,
        train_indices=train,
        validation_indices=validation,
        test_indices=test,
        metadata=metadata,
        horizon=horizon,
        inferred_time_step=time_step,
    )


def make_discretization(delta: float):
    # A state-only invariant requires a reconstruction in which the projected
    # derivative variables can move the center differential states.  Only first
    # derivatives are required here, so a first-order, one-radius Taylor model
    # avoids the unnecessary approximation conflict of the earlier order-2
    # two-radius reconstruction.
    return TaylorNeighborhood(
        deltas=(float(delta),),
        order=1,
        radii=(1.0,),
        aggregation="equal_average",
    )


def _json_ready(value: Any) -> Any:
    if isinstance(value, (np.floating, np.integer)):
        return value.item()
    if isinstance(value, float) and not np.isfinite(value):
        return None
    return value


def _limit_indices(indices: np.ndarray, limit: int | None) -> np.ndarray:
    if limit is None:
        return indices
    if limit < 1:
        raise ValueError("sample limits must be positive")
    if limit >= indices.size:
        return indices
    positions = np.linspace(0, indices.size - 1, limit, dtype=np.int64)
    return np.asarray(indices[positions], dtype=np.int64)


def save_prediction_plot(
    path: Path,
    coordinates: np.ndarray,
    exact: np.ndarray,
    raw: np.ndarray,
    projected: np.ndarray,
    parameters: np.ndarray,
) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    order = np.argsort(coordinates[:, 0])
    t = coordinates[order, 0]
    exact = exact[order]
    raw = raw[order]
    projected = projected[order]
    p = parameters[order]

    def invariant(values: np.ndarray) -> np.ndarray:
        x = np.maximum(values[:, 0], 1.0e-12)
        y = np.maximum(values[:, 1], 1.0e-12)
        return p[:, 3] * x - p[:, 2] * np.log(x) + p[:, 1] * y - p[:, 0] * np.log(y)

    exact_residual = invariant(exact) - p[:, 4]
    raw_residual = invariant(raw) - p[:, 4]
    projected_residual = invariant(projected) - p[:, 4]

    figure, axes = plt.subplots(3, 1, figsize=(9.0, 9.0), constrained_layout=True)
    axes[0].plot(t, exact[:, 0], label="exact prey")
    axes[0].plot(t, raw[:, 0], "--", label="raw prey")
    axes[0].plot(t, projected[:, 0], ":", label="projected prey")
    axes[0].set_ylabel("prey x")
    axes[0].legend(ncol=3)

    axes[1].plot(t, exact[:, 1], label="exact predator")
    axes[1].plot(t, raw[:, 1], "--", label="raw predator")
    axes[1].plot(t, projected[:, 1], ":", label="projected predator")
    axes[1].set_ylabel("predator y")
    axes[1].legend(ncol=3)

    axes[2].plot(t, exact_residual, label="exact")
    axes[2].plot(t, raw_residual, "--", label="raw")
    axes[2].plot(t, projected_residual, ":", label="projected")
    axes[2].set_xlabel("physical time")
    axes[2].set_ylabel(r"$V(x,y)-V_0$")
    axes[2].ticklabel_format(axis="y", style="sci", scilimits=(0, 0))
    axes[2].legend(ncol=3)

    figure.savefig(path, dpi=180)
    plt.close(figure)


