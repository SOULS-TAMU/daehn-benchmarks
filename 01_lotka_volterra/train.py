def main() -> None:
    args = parse_args()
    set_reproducible_seed(int(args.seed))
    if args.epochs < 1:
        raise ValueError("--epochs must be positive")
    if args.pretrain_epochs < 0:
        raise ValueError("--pretrain-epochs must be nonnegative")
    if args.pretrain_epochs >= args.epochs:
        raise ValueError("--pretrain-epochs must be smaller than --epochs")
    if args.batch_size < 1:
        raise ValueError("--batch-size must be positive")
    if args.hidden_size < 1 or args.hidden_layers < 1:
        raise ValueError("network size arguments must be positive")
    if args.learning_rate <= 0.0:
        raise ValueError("--learning-rate must be positive")
    if args.projected_learning_rate <= 0.0:
        raise ValueError("--projected-learning-rate must be positive")
    if args.noise < 0.0:
        raise ValueError("--noise must be nonnegative")
    if args.tolerance <= 0.0:
        raise ValueError("--tolerance must be positive")
    if not 1 <= args.max_iterations <= 100:
        raise ValueError("--max-iterations must lie in [1, 100]")

    dataset = load_dataset(args.data_dir.resolve())
    data = dataset.data
    delta = float(args.delta)
    derivative_step = float(args.derivative_step)
    if not np.isfinite(delta) or delta <= 0.0:
        raise ValueError("--delta must be finite and positive")
    if not np.isfinite(derivative_step) or derivative_step <= 0.0:
        raise ValueError("--derivative-step must be finite and positive")
    if delta >= 0.25 * dataset.horizon:
        raise ValueError("--delta is too large relative to the trajectory horizon")
    if derivative_step >= 0.25 * dataset.horizon:
        raise ValueError(
            "--derivative-step is too large relative to the trajectory horizon"
        )

    train_indices = _limit_indices(dataset.train_indices, args.train_limit)
    validation_indices = _limit_indices(
        dataset.validation_indices, args.validation_limit
    )
    test_indices = _limit_indices(dataset.test_indices, args.test_limit)

    # Full-model central derivatives and the forward Taylor neighborhood must
    # remain inside the time domain. The initial condition is still enforced
    # separately by DAETrainer, so removing boundary samples here does not remove
    # the t=0 condition.
    all_times = np.asarray(data.coordinates[:, 0], dtype=np.float64)
    time_lower = float(np.min(all_times))
    time_upper = float(np.max(all_times))
    interior_margin = float(delta + derivative_step)

    def keep_interior(indices: np.ndarray, split_name: str) -> np.ndarray:
        selected_times = all_times[indices]
        valid = (
            (selected_times >= time_lower + interior_margin)
            & (selected_times <= time_upper - interior_margin)
        )
        filtered = np.asarray(indices[valid], dtype=np.int64)
        if filtered.size == 0:
            raise ValueError(
                f"{split_name} split is empty after applying the stencil "
                f"margin {interior_margin:.6g}"
            )
        removed = int(indices.size - filtered.size)
        if removed:
            print(
                f"  removed {removed} {split_name} samples near time boundaries "
                f"(margin={interior_margin:.6g})"
            )
        return filtered

    train_indices = keep_interior(train_indices, "training")
    validation_indices = keep_interior(validation_indices, "validation")
    test_indices = keep_interior(test_indices, "test")

    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    physical_system = make_lotka_volterra_system(
        dataset.horizon, projection_only=False
    )
    projection_system = make_lotka_volterra_system(
        dataset.horizon, projection_only=True
    )
    discretization = make_discretization(delta)
    compiled_unscaled = compile_dae(
        projection_system,
        discretization=discretization,
        scaling=ScalingConfig(residual_mode="none"),
    )

    # Only the invariant is hard-projected.  The original ODE equations are
    # evaluated by LotkaVolterraTrainer using full-model derivatives.
    projection_row_scales = jnp.asarray(
        (INVARIANT_RESIDUAL_SCALE,), dtype=jnp.float64
    )
    raw_equalities = compiled_unscaled.raw_equalities
    compiled = replace(
        compiled_unscaled,
        residual_scales=projection_row_scales,
        scaled_equalities=lambda context, variables: (
            raw_equalities(context, variables) / projection_row_scales
        ),
    )
    print(
        "  projection row scales: "
        + np.array2string(np.asarray(projection_row_scales), precision=6)
    )
    print(f"  Taylor projection step: {delta:.8e}")
    print(f"  full-model derivative step: {derivative_step:.8e}")

    # Script 10 stores derivative columns as [dx/dt, dy/dt]. DAEHN's derivative
    # closure is deterministic and sorted by state name, giving [dy/dt, dx/dt]
    # for predator_y and prey_x. Reorder targets once so derivative supervision,
    # equation evaluation, prediction files, and labels all agree.
    data_derivative_column = {"prey_x": 0, "predator_y": 1}
    derivative_column_order = np.asarray(
        [
            data_derivative_column[spec.state.name]
            for spec in compiled.discretization.derivatives
        ],
        dtype=np.int64,
    )
    derivative_targets = np.asarray(data.derivatives, dtype=np.float64)[
        :, derivative_column_order
    ]
    derivative_display_name = {
        "prey_x": "dprey_dt",
        "predator_y": "dpredator_dt",
    }
    compiled_derivative_names = tuple(
        derivative_display_name[spec.state.name]
        for spec in compiled.discretization.derivatives
    )
    if compiled_derivative_names != DERIVATIVE_NAMES:
        raise RuntimeError(
            "unexpected compiled derivative order: "
            f"{compiled_derivative_names!r}"
        )
    print(f"  data derivative order: {DATA_DERIVATIVE_NAMES}")
    print(f"  compiled derivative order: {compiled_derivative_names}")

    projection_config = ProjectionConfig(
        tolerance=float(args.tolerance),
        max_iterations=int(args.max_iterations),
        backtracking=bool(args.backtracking),
        implicit_gradient=ImplicitGradientConfig(
            differentiate_problem_parameters=True,
            policy="residual_checked",
            inexact_tolerance=max(float(args.tolerance), 1.0e-7),
            adjoint_tolerance=max(float(args.tolerance), 1.0e-7),
            invalid_batch_policy="use_valid",
        ),
    )
    prepared_projection = compiled.prepare_projection(
        batch_size=int(args.batch_size),
        method=str(args.projection),
        config=projection_config,
        dtype=jnp.float64,
        backend="cpu",
    )

    hidden_sizes = (int(args.hidden_size),) * int(args.hidden_layers)

    # Reproducible disjoint train/validation/test splits on one common horizon.
    all_valid_indices = keep_interior(np.arange(len(all_times), dtype=np.int64), "all")
    train_indices, validation_indices, test_indices, split_info = same_horizon_indices(
        all_times,
        all_valid_indices,
        train_fraction=float(args.train_fraction),
        validation_fraction=float(args.validation_fraction),
        split_mode=str(args.split_mode),
        seed=int(args.split_seed),
        train_limit=args.train_limit,
        validation_limit=args.validation_limit,
        test_limit=args.test_limit,
    )
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    print(
        f"  common train/validation/test horizon: "
        f"[{split_info['horizon_start']:.6g}, {split_info['horizon_end']:.6g}] "
        f"({split_info['split_mode']} split)"
    )

    backbone = TimeScaledMLPBackbone(
        hidden_sizes=hidden_sizes,
        time_scale=dataset.horizon,
        activation=jax.nn.tanh,
    )
    trainer_kwargs = dict(
        physical_system=physical_system,
        compiled=compiled,
        prepared_projection=prepared_projection,
        backbone=backbone,
        initial_coordinates=data.initial_coordinates,
        initial_targets=np.asarray(data.initial_targets)[:, :2],
    )
    train_targets = np.asarray(data.states[train_indices, :2], dtype=np.float64).copy()
    if args.noise > 0.0:
        rng = np.random.default_rng(int(args.seed) + 17)
        train_targets += rng.normal(scale=float(args.noise), size=train_targets.shape)

    run_model_suite(
        example=11,
        system_name=physical_system.name,
        model=args.model,
        trainer_cls=LotkaVolterraTrainer,
        trainer_kwargs=trainer_kwargs,
        train_coordinates=data.coordinates[train_indices],
        train_parameters=data.parameters[train_indices],
        train_targets=train_targets,
        train_derivative_targets=derivative_targets[train_indices],
        validation_coordinates=data.coordinates[validation_indices],
        validation_parameters=data.parameters[validation_indices],
        validation_targets=data.states[validation_indices, :2],
        validation_derivative_targets=derivative_targets[validation_indices],
        evaluation_coordinates=data.coordinates[test_indices],
        evaluation_parameters=data.parameters[test_indices],
        evaluation_targets=data.states[test_indices, :2],
        evaluation_derivative_targets=derivative_targets[test_indices],
        output_dir=output_dir,
        hidden_sizes=hidden_sizes,
        batch_size=int(args.batch_size),
        epochs=int(args.epochs),
        pretrain_epochs=int(args.pretrain_epochs),
        learning_rate=float(args.learning_rate),
        projected_learning_rate=float(args.projected_learning_rate),
        lambda_data=float(args.lambda_data),
        lambda_derivative=float(args.derivative_weight),
        lambda_physics=float(args.violation_weight),
        derivative_steps=(derivative_step,),
        seed=int(args.seed),
        print_every=int(args.print_every),
        validation_every=int(args.validation_every),
        state_names=STATE_NAMES,
        split_info=split_info,
        run_config=vars(args),
        plot=bool(args.plot),
        trajectory_coordinates=data.coordinates[all_valid_indices],
        trajectory_parameters=data.parameters[all_valid_indices],
        trajectory_targets=data.states[all_valid_indices, :2],
        trajectory_derivative_targets=derivative_targets[all_valid_indices],
        case_script=Path(__file__).name,
    )


if __name__ == "__main__":
    main()
