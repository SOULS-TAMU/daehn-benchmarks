r"""Train DAE-HardNet on data generated by script 10.

The physical Lotka--Volterra model is

    dx/dt = alpha*x - beta*x*y,
    dy/dt = -gamma*y + delta*x*y,

with the conserved quantity

    V(x, y) = delta*x - gamma*log(x) + beta*y - alpha*log(y).

The hard algebraic equation used during projected training is

    V(x, y) - V0 = 0,

where V0 is the invariant value at the supplied initial condition.

The script-10 dataset stores [x, y, lambda], but this trainer intentionally
ignores the artificial lambda column.  The projection layer hard-projects the
reconstructed physical state onto

    V(x,y) - V0 = 0,

while the two original Lotka--Volterra differential equations are evaluated
with derivatives of the complete NN -> projection -> reconstruction mapping.
This avoids the nearly singular augmented square system created by adding a
Lagrange multiplier to an invariant that is already conserved by the ODE.

Expected input directory (created by script 10)
------------------------------------------------
    data.npz
    splits.npz
    metadata.json             (optional but recommended)

Example (PowerShell, CPU)
-------------------------
    $env:JAX_PLATFORMS = "cpu"
    $env:CUDA_VISIBLE_DEVICES = ""

    python .\examples\11_lotka_volterra_daehn_training.py `
        --data-dir data\example_10_lotka_volterra `
        --output-dir results\example_11_lotka_volterra_daehn `
        --projection sparse `
        --delta 0.02 `
        --derivative-step 0.01 `
        --epochs 800 `
        --pretrain-epochs 400 `
        --batch-size 32 `
        --hidden-size 64 `
        --hidden-layers 4 `
        --learning-rate 5e-4 `
        --projected-learning-rate 1e-5 `
        --print-every 10 `
        --plot
"""
